// Number of bytes after which a byte no longer influences the 64-bit gear hash.
constexpr std::size_t kGearWindow = 64;
constexpr unsigned kMaxMaskBits = 62;

constexpr std::uint64_t topBitsMask(unsigned bits) noexcept {
    return bits == 0 ? 0 : ~std::uint64_t{0} << (64U - bits);
}

// round(log2(spacing)), computed as floor(log2(1.5 * spacing)).
unsigned maskBitsFor(std::size_t spacing) noexcept {
    if (spacing <= 1) {
        return 0;
    }
    const auto bits = static_cast<unsigned>(std::bit_width(spacing + spacing / 2)) - 1U;
    return std::min(bits, kMaxMaskBits);
}

