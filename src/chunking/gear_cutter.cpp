GearCutter::GearCutter(std::size_t minSize, std::size_t targetSize, std::size_t maxSize) noexcept
    : max_(std::max<std::size_t>(maxSize, 1)) {
    min_ = std::clamp<std::size_t>(minSize, 1, max_);
    normal_ = std::clamp(targetSize, min_, max_);
    warmStart_ = min_ > kGearWindow ? min_ - kGearWindow : 0;

    const unsigned bits = maskBitsFor(normal_ - min_);
    smallBits_ = bits == 0 ? 0 : std::min(bits + 2U, kMaxMaskBits);
    largeBits_ = bits > 2 ? bits - 2U : 0;
    maskSmall_ = topBitsMask(smallBits_);
    maskLarge_ = topBitsMask(largeBits_);
}

GearCutter::Scan GearCutter::scan(State& state, std::span<const std::byte> data) const noexcept {
    const auto* bytes = reinterpret_cast<const std::uint8_t*>(data.data());
    const std::size_t n = data.size();
    std::size_t i = 0;
    std::size_t len = state.length;
    std::uint64_t hash = state.hash;

    // Bytes more than one window before minSize cannot influence any tested hash: skip them.
    if (len < warmStart_) {
        const std::size_t skip = std::min(n, warmStart_ - len);
        i += skip;
        len += skip;
    }
    // Warm the hash on the bytes before minSize; no cut is tested there.
    while (i < n && len + 1 < min_) {
        hash = (hash << 1) + kGearTable[bytes[i++]];
        ++len;
    }
    while (i < n) {
        hash = (hash << 1) + kGearTable[bytes[i++]];
        ++len;
        const std::uint64_t mask = len < normal_ ? maskSmall_ : maskLarge_;
        if ((hash & mask) == 0 || len >= max_) {
            state = State{};
            return Scan{i, true};
        }
    }
    state.hash = hash;
    state.length = len;
    return Scan{i, false};
}

std::size_t GearCutter::nextCut(std::span<const std::byte> data) const noexcept {
    State state;
    return scan(state, data).consumed;
}

